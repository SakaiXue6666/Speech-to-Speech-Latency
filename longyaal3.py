# 把一个 segale 的 segment（segale.src）映射到 source.txt 的哪些句子，从而得到这个 segment 在源音频里的时间范围（start_ms, end_ms）
# 这里假设 segale_src_seg = src_sent j + src_sent j+1 + ...
def _match_src_span_for_seg(segale_src_seg: str,
                            src_sent_list: List[Tuple[int, float, float, List[str]]],
                            list_j: int) -> Tuple[int, int, float, float]:
    """
    用 segale.src 去 source.txt(按句)里“顺序匹配”，确定该 segment 的源时间跨度：
    返回: (new_cursor_sent, num_sent_used, start_ms, end_ms)

    核心思想：
    - segale.src 代表该 segment 对应的源文本片段（通常等于若干句的拼接）
    - 你从 cursor_sent 开始累加句子的 tokens，直到累计 tokens == target tokens（严格相等）
    - 一旦相等，就用第一个句子的 offset 作为 start_ms，用最后一句的 end_ms 作为 end_ms

    ⚠️ 假设非常强：必须严格 token 串相等（标点已去掉）；
       只要出现轻微差异（例如缩写/大小写/分词差），就会走退化策略。
    """
    target = _qwen_units(segale_src_seg, "english")  # Hi, this is Elena. I'm going to xxx. -> [hi, this, is, elena, i, m, going, to, xxx]
    # ---------------------------------------------------\
    if not target:
        # 空 src：退化成“用当前句的时间范围”
        _, s_ms, e_ms, _ = src_sent_list[list_j]
        return list_j + 1, 1, s_ms, e_ms
    # ---------------------------------------------------/
    acc: List[str] = []
    start_ms = None
    end_ms = None
    used = 0
    j = list_j

    # 顺序累加句子直到 token 串等于 target（严格）
    while j < len(src_sent_list):
        _, s_ms, e_ms, toks = src_sent_list[j]  # (j, start, end, [hi, this, is, elena]), (j+1, start, end, [i, m, going, to, xxx])
        if start_ms is None:
            start_ms = s_ms
        end_ms = e_ms
        acc.extend(toks)
        used += 1
        
        if acc == target:
            return j + 1, used, float(start_ms), float(end_ms)

        # ---------------------------------------------------\
        # 如果 acc 已经比 target 长，还没等于，就失败：退化用 1 句
        if len(acc) > len(target) and target:
            break
        # ---------------------------------------------------/
        j += 1

    # ---------------------------------------------------\
    # 退化策略：用 1 句
    _, s_ms, e_ms, _ = src_sent_list[list_j]
    return list_j + 1, 1, float(s_ms), float(e_ms)
    # ---------------------------------------------------/

# 假设 segale_tgt_seg = n * tgt_asr_unit
def _match_tgt_units_for_seg(segale_tgt_seg: str,
                            tgt_asr_units: List[str],
                            unit_i: int,
                            doc_id: str,
                            seg_id: str) -> Tuple[int, int, int]:
    """
    用 segale.tgt（去标点后 tokenized）在 asr_units 里“顺序找连续子串”：
    返回 (new_cursor_unit, u_start, u_end)

    - cursor_unit 保证整体是单调前进的（避免跨段乱匹配）
    - 找不到就退化为空段： (cursor, cursor, cursor)

    ⚠️ 强假设：segale.tgt token 序列必须在 asr_units 里出现为连续子串
       否则该 segment 会在后面被 skip（因为 seg_delays 为空）。
    """

    segale_tgt_seg = _fix_decimal_for_segale_text(segale_tgt_seg)   # ✅ 只修 84. 22
    needle = _qwen_units(segale_tgt_seg, "chinese")  # 嗨，我是丽娜。我将xxx。 -> [嗨, 我, 是, 丽, 娜, 我, 将, xxx]
    # ---------------------------------------------------\
    if not needle:
        return unit_i, unit_i, unit_i
    # ---------------------------------------------------/

    # asr_units: [嗨, 我, 是, 丽, 娜, 我, 将, xxx, ......]
    hit = _find_sublist(tgt_asr_units, needle, unit_i)
    # ---------------------------------------------------\
    if hit is None:
        logger.warning(
            "[skip][tgt-not-found] doc=%s seg_id=%s cursor=%d needle_len=%d needle=%s asr_ctx=%s",
            doc_id, seg_id, unit_i,
            len(needle), needle[:20],
            tgt_asr_units[unit_i: min(len(tgt_asr_units), unit_i + 60)]
        )
        # 找不到：退化为空
        return unit_i, unit_i, unit_i
    # ---------------------------------------------------/
    u_start, u_end = hit
    return u_end, u_start, u_end


