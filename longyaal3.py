# 关键新增：为了把 segale -> unit 下标 -> 切 delays
# ============================================================
def _to_ms(x: Any) -> float:
    """
    把长度/时间统一到毫秒：
    - x=None / 无法转 float / <=0 -> INF
    - 小于 1e4 的认为是“秒”，乘 1000
      （因为很多 instances.log 里 source_length 是秒，而 delays 常是 ms）
    - >=1e4 的认为已经是 ms
    ⚠️ 隐含假设：秒不会超过 1e4（也就是 10000 秒 ≈ 2.7 小时）。
    """
    if x is None:
        return INF
    try:
        v = float(x)
    except Exception:
        return INF
    if v <= 0:
        return INF
    # instances.log 里 source_length / prediction_length 常见是秒；delays 是 ms
    if v < 1e4:
        return v * 1000.0
    return v


# ============================================================
def _fix_decimal_for_segale_text(s: str) -> str:
    """
    只修 segale 里常见的小数拆分：
      "84. 22" / "84 .22" / "84 . 22"  -> "84.22"
    不改其它标点/空格/分词规则。
    """
    s = _norm(s)
    return re.sub(r"(?<=\d)\s*\.\s*(?=\d)", ".", s)


# 统一字符形态
def _norm(s: str) -> str:
    """Unicode 归一化：把全角半角、兼容字符统一（NFKC 常用）。"""
    return unicodedata.normalize("NFKC", s or "")


def _find_sublist(hay: List[str], needle: List[str], start: int) -> Optional[Tuple[int, int]]:
    """
    在 hay[start:] 里找 needle 的连续匹配，返回 (s, e) half-open。
    举例：hay=[a,b,c,d], needle=[c,d] -> 返回 (2,4)
    """
    if not needle:
        return None
    n = len(needle)
    # i 的上界要保证 hay[i:i+n] 不越界
    for i in range(start, max(start, len(hay) - n) + 1):
        if hay[i:i + n] == needle:  # 👈 会不会严格了点？？？
            return i, i + n
    return None


